/**
 * The detectors that decide whether a byte may be published, and the set of
 * bytes they run over.
 *
 * **Why this is a module and not a test.** Three callers need the same answer
 * and must not be able to drift apart: `test/published-prose.test.ts` (the
 * working tree), `scripts/verify-commit-messages.mjs` (the messages of the
 * commits being pushed) and any future check over a downloaded tarball. A
 * second copy of these patterns is a second policy, and the weaker one always
 * wins.
 *
 * ## The scanned set is computed from where the bytes go, never from a list of
 * directory names
 *
 * The guard this replaces named three directories — `src`, `test`, `scripts` —
 * plus six literal markdown filenames. Ten tracked files sat outside it,
 * including `.gitlab-ci.yml`, the one file that had actually carried the
 * internal host, and `package.json`, which had carried it in a
 * `devDependencies` specifier on the registry. A named list is a requirement
 * about a set guarded by examples.
 *
 * So the set is the union of three questions asked of the tools that answer
 * them:
 *
 * | set | asked of | what it is |
 * |---|---|---|
 * | `packed` | `npm pack --dry-run --json` | the bytes npm serves |
 * | `tracked` | `git ls-files` | the bytes a public mirror gets |
 * | `built` | a walk of every directory in `package.json`'s `files` | the generated bytes, which git does not know about |
 *
 * A file in none of the three is out of scope. A file in any of them is
 * scanned. Nothing chooses.
 *
 * ## Two scopes, decided by extension, and every file must land in one
 *
 * A source file addresses a stranger reading the code. A README, a changelog or
 * a CI file legitimately addresses *this repository's own* reader — `SECURITY.md`
 * opens "This repository is the TypeScript SDK", and a guard that reddened on
 * that would be demanding the document stop being about itself. So:
 *
 * - **code** (`.ts .mts .cts .js .mjs .cjs .json`): every detector.
 * - **document** (`.md .yml .yaml`, and files with no extension such as
 *   `LICENSE`): the MARKER detectors only.
 *
 * `scopeOf` throws on anything it cannot classify, so a new extension is a
 * decision somebody makes rather than a file that silently stops being scanned.
 *
 * ## Stripping happens for one detector, not for all of them
 *
 * The predecessor stripped URLs *and* inline code spans from every markdown
 * line before every class. That made the six shipped documents blind to exactly
 * the shapes an internal host, a developer path or an internal id take in a
 * README — a link and a backticked citation. `[source](https://<internal
 * host>/…)` was invisible.
 *
 * Only the German scan strips, and it strips two things: URL-ish runs (several
 * German function words are also ordinary path segments — `/api/v1/von/`,
 * `/nach/`, `/bei/`) and **single-token** code spans (a backticked lone token is
 * a citation, and a changelog has to be able to say that a detector stopped
 * tripping on `von`). A multi-word code span is left in, because a backticked
 * German sentence is still a German sentence.
 *
 * ## Every detector carries its own fixtures
 *
 * `DETECTORS` is a list of objects, not two parallel arrays, so a detector
 * cannot be added without a `mustMatch` and a `mustNotMatch`. Seven of the
 * fifteen patterns in the predecessor had neither, and two of them could be
 * deleted outright with the whole suite green. `DETECTOR_FLOOR` below is the
 * anti-vacuity floor: deleting a detector is red.
 */

